export function exampleRootReadme(
  actionRef: string,
  login: string,
  templates: readonly { readonly name: string; readonly title: string }[],
): string {
  const [action = actionRef, version = ""] = actionRef.split("@");
  return [
    "# Readmint template test",
    "",
    `The Readmint profile templates, rendered by the [Readmint Action](https://github.com/${action}) \`${version}\``,
    `with live data of ${login}. The workflow in \`.github/workflows/readmint.yml\` renders every section daily and on demand`,
    "and commits the SVGs; light and dark follow your GitHub theme.",
    "",
    ...templates.map(({ name, title }) => `- [${title}](${name}/README.md)`),
    "",
    "Each template folder holds its designs (with the personal texts filled in) in `designs/` and the rendered output in",
    "`readmint/`. To use one, copy its `designs/` folder and its job step into your profile repository.",
    "",
    "The `designs/` folders and the READMEs are generated by `readmint-examples` from `packages/components/templates/profiles`",
    `in [${action}](https://github.com/${action}) and must not be edited by hand.`,
    "",
  ].join("\n");
}

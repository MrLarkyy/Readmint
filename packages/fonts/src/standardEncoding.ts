const upperSids = new Map(upper);

/** The standard string id a Standard Encoding code names (what `seac` refers to), or 0 for none. */
export function standardEncodingSid(code: number): number {
  if (code >= 32 && code <= 126) return code - 31;
  return upperSids.get(code) ?? 0;
}
